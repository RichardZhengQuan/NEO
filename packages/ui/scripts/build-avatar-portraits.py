#!/usr/bin/env python3
"""Build the inline avatar portraits from the source art.

Reads packages/ui/assets/avatar-art/<kind>.webp (square portraits on a flat
background), cuts the background out, shrinks each to 384 px, and writes
packages/ui/src/avatar/portraits.data.ts with the results as WebP data URIs.

Run it after changing the art:  python3 packages/ui/scripts/build-avatar-portraits.py
Needs Python 3 and Pillow built with WebP support.
"""
import base64
import io
from collections import deque
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / 'assets' / 'avatar-art'
OUT = ROOT / 'src' / 'avatar' / 'portraits.data.ts'
KINDS = ['robot', 'cat', 'dog', 'boy', 'girl']

WORK_PX = 512        # cut out at this size
OUT_PX = 384         # ship at this size (2–3× the largest on-screen avatar)
QUALITY = 80
FLOOD = 16           # how close (RGB distance) to the background color counts as background
POCKET, POCKET_MIN = 9, 12   # enclosed background pockets: tighter match, minimum area
EDGE_BAND = 2        # px around the background that get partial alpha


def dist(a, b):
    return ((a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2 + (a[2] - b[2]) ** 2) ** 0.5


def cut_out(path: Path) -> Image.Image:
    im = Image.open(path).convert('RGB').resize((WORK_PX, WORK_PX), Image.LANCZOS)
    w = h = WORK_PX
    px = list(im.getdata())
    border = [px[x] for x in range(w)] + [px[(h - 1) * w + x] for x in range(w)] \
        + [px[y * w] for y in range(h)] + [px[y * w + w - 1] for y in range(h)]
    bgc = tuple(sorted(c[i] for c in border)[len(border) // 2] for i in range(3))
    d = [dist(c, bgc) for c in px]

    def nbrs(i):
        x, y = i % w, i // w
        if x > 0: yield i - 1
        if x < w - 1: yield i + 1
        if y > 0: yield i - w
        if y < h - 1: yield i + w

    # Background connected to the edges.
    bg = bytearray(w * h)
    q = deque()
    for i in range(w * h):
        x, y = i % w, i // w
        if (x in (0, w - 1) or y in (0, h - 1)) and d[i] < FLOOD:
            bg[i] = 1
            q.append(i)
    while q:
        i = q.popleft()
        for j in nbrs(i):
            if not bg[j] and d[j] < FLOOD:
                bg[j] = 1
                q.append(j)

    # Enclosed pockets of background (between hair strands, whiskers).
    seen = bytearray(w * h)
    for i in range(w * h):
        if bg[i] or seen[i] or d[i] >= POCKET:
            continue
        comp, q = [i], deque([i])
        seen[i] = 1
        while q:
            k = q.popleft()
            for j in nbrs(k):
                if not seen[j] and not bg[j] and d[j] < POCKET:
                    seen[j] = 1
                    comp.append(j)
                    q.append(j)
        if len(comp) >= POCKET_MIN:
            for k in comp:
                bg[k] = 1

    # Anti-aliased edges: alpha from the distance to the background color,
    # and the background tint removed from the color.
    band = bytearray(w * h)
    frontier = [i for i in range(w * h) if bg[i]]
    for _ in range(EDGE_BAND):
        nxt = []
        for i in frontier:
            for j in nbrs(i):
                if not bg[j] and not band[j]:
                    band[j] = 1
                    nxt.append(j)
        frontier = nxt

    out = []
    for i, c in enumerate(px):
        if bg[i]:
            out.append((0, 0, 0, 0))
        elif band[i]:
            a = max(0.0, min(1.0, (d[i] - 8) / 70))
            if a <= 0.02:
                out.append((0, 0, 0, 0))
            else:
                out.append(tuple(int(max(0, min(255, bgc[k] + (c[k] - bgc[k]) / a))) for k in range(3)) + (int(a * 255),))
        else:
            out.append(c + (255,))
    res = Image.new('RGBA', (w, h))
    res.putdata(out)
    return res.resize((OUT_PX, OUT_PX), Image.LANCZOS)


def main():
    lines = [
        '// Generated by packages/ui/scripts/build-avatar-portraits.py from packages/ui/assets/avatar-art.',
        '// Do not edit by hand: change the art and run the script.',
        "import type { AvatarCharacter } from './config.js';",
        '',
        'export const PORTRAITS: Record<AvatarCharacter, string> = {',
    ]
    for kind in KINDS:
        buf = io.BytesIO()
        cut_out(ART / f'{kind}.webp').save(buf, 'WEBP', quality=QUALITY, method=6)
        data = buf.getvalue()
        print(f'{kind}: {len(data) / 1024:.1f} KB')
        lines.append(f"  {kind}: 'data:image/webp;base64,{base64.b64encode(data).decode()}',")
    lines += ['};', '']
    OUT.write_text('\n'.join(lines))
    print('wrote', OUT.relative_to(ROOT))


if __name__ == '__main__':
    main()
